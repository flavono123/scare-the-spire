-- Supabase exit step 5 (docs/SUPABASE_EXIT_PLAN.md 7.3, docs/supabase-exit/D1_SCHEMA_DESIGN.md 5.5):
-- what the D1 -> Supabase mirror needs on the Supabase side. Additive only; nothing the site calls
-- today changes. Rollback: docs/release/d1-step5-mirror/rollback_d1_step5_mirror.sql.
--
-- 1. puzzlebox_runs.id accepts the D1 run ids ([2^40, 2^53)); the identity still numbers rows
--    Supabase itself inserts (after a step 5 rollback).
-- 2. mirror_favorite_tournament_play: the play row (a seen id is ignored), play_count recounted from
--    the play rows, and the candidate stats D1 computed upserted as state. Supabase never recomputes
--    the stats (two stores computing them would differ in rank_history.at and tie order).
-- 3. mirror_run(text): a shared run as "<row JSON>\n<raw>" in a text/plain body, so the raw (up to
--    1.9 MB) is sent without JSON escaping and never sits in a D1 outbox row.
-- Only service_role may call the functions.

alter table public.puzzlebox_runs alter column id set generated by default;

create or replace function public.mirror_favorite_tournament_play(p_env text, p_play jsonb, p_stats jsonb)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_tournament uuid := (p_play ->> 'tournament_id')::uuid;
begin
  if p_env is null or p_env not in ('production', 'development') then
    raise exception 'unknown env' using errcode = '22023';
  end if;
  if jsonb_typeof(p_stats) is distinct from 'array' then
    raise exception 'stats must be an array' using errcode = '22023';
  end if;

  insert into public.favorite_tournament_plays (
    id, tournament_id, user_id, env, starting_size, champion_type, champion_id, matches, created_at
  ) values (
    (p_play ->> 'id')::uuid, v_tournament, (p_play ->> 'user_id')::uuid, p_env,
    (p_play ->> 'starting_size')::integer, p_play ->> 'champion_type', p_play ->> 'champion_id',
    p_play -> 'matches', (p_play ->> 'created_at')::timestamptz
  )
  on conflict (id) do nothing;

  update public.favorite_tournament_posts
    set play_count = (
      select count(*) from public.favorite_tournament_plays
      where tournament_id = v_tournament and env = p_env
    )
    where id = v_tournament and env = p_env;

  insert into public.favorite_tournament_candidate_stats (
    tournament_id, env, resource_type, resource_id, match_appearances, match_wins, championships,
    current_rank, rank_history
  )
  select v_tournament, p_env, s ->> 'resource_type', s ->> 'resource_id',
         (s ->> 'match_appearances')::integer, (s ->> 'match_wins')::integer, (s ->> 'championships')::integer,
         (s ->> 'current_rank')::integer, coalesce(s -> 'rank_history', '[]'::jsonb)
  from jsonb_array_elements(p_stats) as e(s)
  on conflict (tournament_id, env, resource_type, resource_id) do update set
    match_appearances = excluded.match_appearances,
    match_wins = excluded.match_wins,
    championships = excluded.championships,
    current_rank = excluded.current_rank,
    rank_history = excluded.rank_history;

  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.mirror_run(text)
returns void
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_cut integer := position(E'\n' in $1);
  v_row jsonb;
  v_raw text;
begin
  if v_cut = 0 then
    raise exception 'mirror_run needs "<row JSON>\n<raw>"' using errcode = '22023';
  end if;
  v_row := substring($1 from 1 for v_cut - 1)::jsonb;
  v_raw := substring($1 from v_cut + 1);
  if v_row ->> 'env' is null or v_row ->> 'env' not in ('production', 'development') then
    raise exception 'unknown env' using errcode = '22023';
  end if;

  insert into public.runs as r (
    id, env, raw, seed, build, "character", ascension, win, start_time, run_time, acts_count, total_floors,
    donor_user_id, donor_nickname, created_at, badges, cover_spec
  ) values (
    v_row ->> 'id', v_row ->> 'env', v_raw, v_row ->> 'seed', v_row ->> 'build', v_row ->> 'character',
    (v_row ->> 'ascension')::integer, (v_row ->> 'win')::boolean, (v_row ->> 'start_time')::bigint,
    (v_row ->> 'run_time')::integer, (v_row ->> 'acts_count')::integer,
    coalesce((v_row ->> 'total_floors')::integer, 0), (v_row ->> 'donor_user_id')::uuid,
    coalesce(v_row ->> 'donor_nickname', '닉'), coalesce((v_row ->> 'created_at')::timestamptz, now()),
    coalesce(v_row -> 'badges', '[]'::jsonb),
    case when jsonb_typeof(v_row -> 'cover_spec') = 'object' then v_row -> 'cover_spec' end
  )
  on conflict (id, env) do update set
    raw = excluded.raw,
    seed = excluded.seed,
    build = excluded.build,
    "character" = excluded."character",
    ascension = excluded.ascension,
    win = excluded.win,
    start_time = excluded.start_time,
    run_time = excluded.run_time,
    acts_count = excluded.acts_count,
    total_floors = excluded.total_floors,
    donor_nickname = excluded.donor_nickname,
    badges = excluded.badges,
    cover_spec = excluded.cover_spec
  where r.donor_user_id is not distinct from excluded.donor_user_id;
end;
$$;

revoke all on function public.mirror_favorite_tournament_play(text, jsonb, jsonb) from public, anon, authenticated;
revoke all on function public.mirror_run(text) from public, anon, authenticated;
grant execute on function public.mirror_favorite_tournament_play(text, jsonb, jsonb) to service_role;
grant execute on function public.mirror_run(text) to service_role;
